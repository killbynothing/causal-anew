def has_module(mod):
    try:
        __import__(mod)
        return True
    except Exception:
        return False


def skip_reason(v):
    """返回 SKIP 原因字符串；可跑则返回 None。"""
    if v.get("need_file"):
        if not os.path.exists(os.path.join(ROOT, v["need_file"])):
            return f"未建：{v['need_file']}"
    if v.get("need_db") and not os.path.exists(DB):
        return "缺 data/world_truth.db"
    for mod in v.get("need", []):
        if not has_module(mod):
            return f"缺依赖 {mod}（pip install {mod} --break-system-packages）"
    return None


def relevant(v, changed):
    """文件改动是否触发该验证器。"""
    triggers = [_norm_changed_path(t) for t in v["triggers"]]
    for c in (_norm_changed_path(item) for item in changed):
        for trig in triggers:
            if trig == c:
                return True
            trig_dir = trig.rstrip("/")
            changed_dir = c.rstrip("/")
            if changed_dir and trig.startswith(changed_dir + "/"):
                return True
            if trig_dir and c.startswith(trig_dir + "/"):
                return True
            if "/" not in c and trig.rsplit("/", 1)[-1] == c:
                return True
    return False


def _norm_changed_path(path):
    """Normalize --changed input to a repo-relative POSIX path."""
    text = str(path or "").replace("\\", "/")
    root = ROOT.replace("\\", "/").rstrip("/")
    if text.lower().startswith((root + "/").lower()):
        text = text[len(root) + 1:]
    while text.startswith("./"):
        text = text[2:]
    return text


def _normalize_output(text):
    return (text or "").rstrip()


def run_one(v):
    sk = skip_reason(v)
    if sk:
        return {"id": v["id"], "status": "skip", "elapsed_s": 0.0, "detail": sk, "stdout": "", "stderr": ""}

    started = time.perf_counter()
    timeout_s = v.get("timeout_s", DEFAULT_TIMEOUT_BY_TIER.get(v["tier"], 300))
    try:
        r = subprocess.run(
            v["cmd"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout_s,
        )
        return {
            "id": v["id"],
            "status": "pass" if r.returncode == 0 else "fail",
            "elapsed_s": time.perf_counter() - started,
            "detail": "PASS" if r.returncode == 0 else f"FAIL (exit {r.returncode})",
            "stdout": _normalize_output(r.stdout),
            "stderr": _normalize_output(r.stderr),
        }
    except subprocess.TimeoutExpired as e:
        return {
            "id": v["id"],
            "status": "fail",
            "elapsed_s": time.perf_counter() - started,
            "detail": f"TIMEOUT ({timeout_s}s)",
            "stdout": _normalize_output(e.stdout),
            "stderr": _normalize_output(e.stderr),
        }
    except FileNotFoundError as e:
        return {
            "id": v["id"],
            "status": "skip",
            "elapsed_s": time.perf_counter() - started,
            "detail": f"command unavailable: {e}",
            "stdout": "",
            "stderr": "",
        }


def print_result(v, result):
    print(f"\n== [{v['id']}] {v['desc']}")
    if result["stdout"]:
        print(result["stdout"])
    if result["stderr"]:
        print(result["stderr"], file=sys.stderr)
    print(f"   {result['detail']} | {result['elapsed_s']:.2f}s")


def main():
    ap = argparse.ArgumentParser(description="Unified verification gate")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--quick", action="store_true", help="Run quick validators")
    g.add_argument("--full", action="store_true", help="Run full validators")
    g.add_argument("--list", action="store_true", help="List validators")
    ap.add_argument("--changed", nargs="*", default=None, help="Run validators relevant to changed files")
    args = ap.parse_args()

    if args.list:
        for v in VALIDATORS:
            print(f"[{v['tier']:5}] {v['id']:24} -> {', '.join(v['triggers'])}")
        return 0

    if args.changed is not None:
        chosen = [v for v in VALIDATORS if v["tier"] == "quick" and relevant(v, args.changed)]
        scope = f"--changed {args.changed}"
        if not chosen:
            print(f"verify: no validators matched {args.changed}")
            return 0
    elif args.full:
        chosen = VALIDATORS
        scope = "--full"
    else:
        chosen = [v for v in VALIDATORS if v["tier"] == "quick"]
        scope = "--quick"

    print(f"verify.py [{scope}] :: {len(chosen)} validators")
    results = {}
    if len(chosen) <= 1:
        for v in chosen:
            result = run_one(v)
            results[v["id"]] = result
            print_result(v, result)
    else:
        max_workers = min(len(chosen), MAX_PARALLEL_VALIDATORS)
        print(f"parallel workers: {max_workers}")
        by_id = {v["id"]: v for v in chosen}
        with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as ex:
            futures = {ex.submit(run_one, v): v["id"] for v in chosen}
            for fut in concurrent.futures.as_completed(futures):
                result = fut.result()
                results[result["id"]] = result
                print_result(by_id[result["id"]], result)

    npass = sum(1 for r in results.values() if r["status"] == "pass")
    nfail = sum(1 for r in results.values() if r["status"] == "fail")
    nskip = sum(1 for r in results.values() if r["status"] == "skip")

    for v in chosen:
        r = results[v["id"]]
        mark = {"pass": "[OK]", "fail": "[!!]", "skip": "[--]"}[r["status"]]
        print(f"  {mark} {v['id']} ({r['elapsed_s']:.2f}s)")

    print(f"\n  PASS {npass} | FAIL {nfail} | SKIP {nskip}")
    if nfail:
        print("\n[red] validator failure detected")
        return 1
    print("\n[green] all selected validators passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
